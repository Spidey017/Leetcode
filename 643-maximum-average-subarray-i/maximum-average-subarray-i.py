class Solution:
    def findMaxAverage(self, nums: List[int], k: int) -> float:

        i=0
        s=0
        large=float('-inf')

        for j in range(len(nums)):
            s=s+nums[j]

            if j-i+1==k:
                avg=s/k

                if avg>large:
                    large=avg

                s=s-nums[i]
                i=i+1

        return large

                    

                

        



































































































































































































































































        
        